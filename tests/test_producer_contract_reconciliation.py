def test_security_audit_native_event_still_persists(db_session):
    """A real AuditEvent, constructed the way AuditLogger.log() always has
    (PR4.1/4.1.5), must still parse and persist exactly as before -- PR4.5
    only reconciles the gateway producer, it must not touch this path."""
    native_event = AuditEvent(
        service="omnibioai-auth", event_type="auth_login", user_id="u1",
        action="login", decision="success",
    )
    raw = json.dumps(native_event.model_dump(mode="json"))

    parsed = parse_audit_event(raw)
    result = Sink(db_session).write(parsed.model_dump())

    assert result is True
    row = db_session.get(AuditEventRecord, native_event.event_id)
    assert row.service == "omnibioai-auth"


# ---------------------------------------------------------------------------
# No duplicate schema paths on the consumer side: one function, one code
# path, handles both producers -- no format-sniffing/branching needed.
# ---------------------------------------------------------------------------

def test_gateway_and_security_audit_events_use_the_identical_parse_function(db_session):
    """Both producer shapes go through the exact same parse_audit_event /
    Sink.write call with no producer-specific branch -- this test would
    fail to compile/run meaningfully if the two needed different handling,
    since it calls both through one shared helper."""

    def _round_trip(raw_json: str) -> AuditEventRecord:
        parsed = parse_audit_event(raw_json)
        Sink(db_session).write(parsed.model_dump())
        return db_session.get(AuditEventRecord, parsed.event_id)

    gateway_raw = _gateway_shaped_payload(event_type="request")
    native_raw = json.dumps(
        AuditEvent(service="policy", event_type="policy_decision").model_dump(mode="json")
    )

    gateway_row = _round_trip(gateway_raw)
    native_row = _round_trip(native_raw)

    assert gateway_row is not None
    assert native_row is not None
    assert gateway_row.event_id != native_row.event_id
